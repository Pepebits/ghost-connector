import { t } from '../../i18n/index.js';
import { TERMINAL_JOB_STATES, type JobEventRecord, type JobRecord } from '../../db/jobs.js';
import { jobStateBadge } from './badge.js';
import { html, raw } from '../html.js';
import { layout } from './layout.js';
import { clockTime, pageHeader } from './ui.js';
import { cancelJobControl, JOB_TYPE_LABELS, jobDuration, jobOptions, jobParams, jobRunId, jobTarget, timeTag } from './jobInfo.js';

const LOG_TONE: Record<string, string> = { warn: 'text-warn', error: 'text-err' };

function eventLine(e: JobEventRecord): string {
  return html`<div class="log-line whitespace-pre-wrap break-words py-0.5 ${LOG_TONE[e.level] ?? ''}" data-level="${e.level}">[${clockTime(e.at)}] ${e.message}</div>`;
}

/** Final status of each post from its last event with postId (planned/failed/applied...). */
function postOutcomes(events: JobEventRecord[]): Map<string, { level: string; message: string }> {
  const out = new Map<string, { level: string; message: string }>();
  for (const e of events) {
    if (!e.data_json) continue;
    try {
      const data = JSON.parse(e.data_json) as { postId?: string; status?: string; kind?: string };
      if (data.postId && (data.status || data.kind || e.level !== 'info')) out.set(data.postId, { level: e.level, message: e.message });
    } catch {
      // corrupt data_json: that event is ignored
    }
  }
  return out;
}

export interface JobConsoleOpts {
  job: JobRecord;
  events: JobEventRecord[];
  titles: Map<string, string>;
}

export function jobConsolePage(opts: JobConsoleOpts): string {
  const { job, events, titles } = opts;
  const isTerminal = TERMINAL_JOB_STATES.includes(job.state);
  const lastId = events.at(-1)?.id ?? 0;
  const params = jobParams(job);
  const postIds = job.type === 'sync' ? [] : (params.postIds ?? []);
  const singlePostId = job.type === 'plan' && postIds.length === 1 ? postIds[0]! : null;

  const warnCount = events.filter((e) => e.level === 'warn').length;
  const errorCount = events.filter((e) => e.level === 'error').length;

  const cancelForm = !isTerminal
    ? cancelJobControl(job.id)
    : '';

  // Affected posts, each with its result (if finished) and link.
  const outcomes = postOutcomes(events);
  const postItems = postIds
    .map((id) => {
      const outcome = outcomes.get(id);
      const tone = outcome ? (outcome.level === 'error' ? 'text-err' : outcome.level === 'warn' ? 'text-warn' : 'text-ok') : 'text-muted';
      const target = job.type === 'plan' ? '#plan-preview' : '';
      return html`<li class="flex flex-wrap items-baseline justify-between gap-2 border-b border-line py-1.5 last:border-b-0">
        <a href="/posts/${id}${target}">${titles.get(id) ?? id}</a>
        <span class="text-xs ${tone}">${outcome ? outcome.message.replace(/^"[^"]*":\s*/, '') : isTerminal ? t('jobs.console.noResult') : t('jobs.console.pending')}</span>
      </li>`;
    })
    .join('');
  const postsBlock = postIds.length
    ? html`<div><h2 class="section-heading !mb-1 text-sm">${t('jobs.console.posts', { count: postIds.length })}</h2><ul class="text-sm">${raw(postItems)}</ul></div>`
    : '';

  const options = jobOptions(job);
  const instructions = params.extraInstructions
    ? html`<div><h2 class="section-heading !mb-1 text-sm">${t('jobs.console.instructions')}</h2>
        <blockquote class="whitespace-pre-wrap border-l-[3px] border-accent px-3 text-sm text-muted">${params.extraInstructions}</blockquote></div>`
    : '';
  const runId = jobRunId(job);

  const errorBox = job.error ? html`<div class="issue issue-error"><div class="issue-message"><strong>${t('jobs.console.jobFailed')}</strong> ${job.error}</div></div>` : '';

  const total = job.total || 1;
  const pct = Math.min(100, Math.round((job.done / total) * 100));

  // Deliberately JS content, not HTML: job.id is a UUID generated by the
  // server (randomUUID), safe to interpolate without going through the HTML
  // escaping of the `html` tag (which would break the JSON.stringify in here).
  // The total of a "sync" job isn't known until it finishes
  // listing Ghost (it may still be 0 when this page loads); in that
  // case liveTotal=0 is sent so the script does NOT try to update
  // live progress with a still-invalid denominator. plan/apply
  // always know their total from the moment they're enqueued.
  const liveTotal = job.type === 'sync' && job.total === 0 ? 0 : total;
  // Single-post plan: the draft is shown while the writer writes and,
  // when done, it jumps straight to the post's preview.
  const liveOpts = singlePostId ? { postId: singlePostId, redirectTo: `/posts/${singlePostId}#plan-preview` } : {};
  const streamScript = !isTerminal
    ? // No inline script (the CSP only runs the panel's own files): jobs.js starts from these data.
      html`<div hidden data-job-stream="${JSON.stringify({ id: job.id, lastId, done: job.done, total: liveTotal, opts: liveOpts })}"></div><script src="/jobs.js" data-cfasync="false"></script>`
    : '';
  const livePanel =
    singlePostId && !isTerminal
      ? html`<section class="mb-6">
          <h2 class="section-heading">${t('jobs.console.liveDraft')} <span id="live-draft-status" class="font-normal text-sm text-muted">${t('jobs.console.waitingWriter')}</span></h2>
          <div id="live-draft" class="article-preview"><p class="text-muted">${t('jobs.console.liveDraftEmpty')}</p></div>
        </section>`
      : '';

  const nextAction =
    isTerminal && singlePostId
      ? html`<a class="btn" href="/posts/${singlePostId}#plan-preview">${t('jobs.console.viewResult')}</a>`
      : isTerminal && job.type === 'sync'
        ? html`<a class="btn" href="/">${t('jobs.console.viewDrafts')}</a>`
        : '';

  const filterButton = (level: string, label: string, count?: number) =>
    html`<button type="button" class="btn btn-ghost btn-sm${level === 'all' ? ' is-active' : ''}" data-log-filter="${level}" aria-pressed="${level === 'all' ? 'true' : 'false'}">${label}${count !== undefined ? ` (${count})` : ''}</button>`;

  const body = html`
    ${raw(
      pageHeader({
        back: { href: '/jobs', label: t('common.nav.jobs') },
        title: `${JOB_TYPE_LABELS[job.type]}: ${jobTarget(job, titles)}`,
        badge: html`<span id="job-state">${raw(jobStateBadge(job.state))}</span>`,
        meta: html`${raw(t('jobs.console.meta', { time: timeTag(job.created_at), duration: html`${jobDuration(job)}` }))}${job.created_by ? ` · ${t('auth.by', { name: job.created_by })}` : ''}${options.length ? ` · ${options.join(' · ')}` : ''}${runId ? ` · ${runId}` : ''}`,
        actions: nextAction + cancelForm,
      }),
    )}
    ${raw(errorBox)}
    <div class="mb-1 flex justify-between text-sm text-muted"><span>${t('jobs.console.progress')}</span><span id="job-progress" class="tabular-nums">${job.done}/${job.total}</span></div>
    <div class="mb-5 h-2 overflow-hidden rounded-full bg-line" role="progressbar" aria-label="${t('jobs.console.progressLabel')}" aria-valuemin="0" aria-valuemax="${job.total}" aria-valuenow="${job.done}">
      <div id="job-progress-fill" class="h-full bg-accent transition-[width] duration-300" style="width:${pct}%"></div>
    </div>
    ${postsBlock || instructions ? raw(html`<div class="card mb-6 grid gap-4 p-4 lg:grid-cols-2">${raw(postsBlock)}${raw(instructions)}</div>`) : ''}
    ${raw(livePanel)}
    <section aria-labelledby="log-title">
      <div class="mb-2 flex flex-wrap items-center justify-between gap-2">
        <h2 id="log-title" class="section-heading !mb-0">${t('jobs.console.log')}</h2>
        <div class="flex gap-1.5" role="group" aria-label="${t('jobs.console.filterLog')}">
          ${raw(filterButton('all', t('jobs.console.filter.all')))}
          ${raw(filterButton('warn', t('jobs.console.filter.warn'), warnCount + errorCount))}
          ${raw(filterButton('error', t('jobs.console.filter.error'), errorCount))}
        </div>
      </div>
      <div id="log" data-log class="max-h-[55vh] min-h-32 overflow-y-auto rounded-md border border-line bg-log px-4 py-3 font-mono text-[0.82rem]" tabindex="0" aria-label="${t('jobs.console.logLabel')}">${raw(events.map(eventLine).join('\n'))}</div>
    </section>
    <script src="/job-log.js" defer data-cfasync="false"></script>
    ${raw(streamScript)}
  `;

  return layout({ title: t('jobs.console.pageTitle', { type: JOB_TYPE_LABELS[job.type], id: job.id.slice(0, 8) }), bodyHtml: body, section: 'jobs' });
}
